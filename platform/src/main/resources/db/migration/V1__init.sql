CREATE TABLE run_manifest (
    run_id VARCHAR(80) PRIMARY KEY,
    scenario_id VARCHAR(80) NOT NULL,
    clock_mode VARCHAR(16) NOT NULL,
    epoch_start VARCHAR(32) NOT NULL,
    tick_ms BIGINT NOT NULL,
    tick BIGINT NOT NULL,
    master_seed BIGINT NOT NULL,
    mock_mode BOOLEAN NOT NULL,
    created_at VARCHAR(32) NOT NULL
);

CREATE TABLE id_sequence (
    run_id VARCHAR(80) NOT NULL,
    entity VARCHAR(32) NOT NULL,
    seq BIGINT NOT NULL,
    PRIMARY KEY (run_id, entity)
);

CREATE TABLE site_node (
    id VARCHAR(160) PRIMARY KEY,
    run_id VARCHAR(80) NOT NULL,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    x_m DECIMAL(12, 2) NOT NULL,
    y_m DECIMAL(12, 2) NOT NULL
);

CREATE TABLE device (
    id VARCHAR(160) PRIMARY KEY,
    run_id VARCHAR(80) NOT NULL,
    site_id VARCHAR(160) NOT NULL,
    code VARCHAR(64) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL
);

CREATE TABLE event (
    id VARCHAR(160) PRIMARY KEY,
    run_id VARCHAR(80) NOT NULL,
    device_id VARCHAR(160) NOT NULL,
    site_id VARCHAR(160) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    occurred_at VARCHAR(32) NOT NULL,
    tick BIGINT NOT NULL
);

CREATE INDEX idx_event_run ON event (run_id, tick, id);

CREATE TABLE outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(80) NOT NULL,
    event_id VARCHAR(160) NOT NULL,
    payload VARCHAR(2000) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at VARCHAR(32) NOT NULL,
    published_at VARCHAR(32)
);

CREATE INDEX idx_outbox_status ON outbox (status, id);

CREATE TABLE agent_run (
    id VARCHAR(160) PRIMARY KEY,
    run_id VARCHAR(80) NOT NULL UNIQUE,
    task VARCHAR(500) NOT NULL,
    status VARCHAR(32) NOT NULL,
    mock_mode BOOLEAN NOT NULL,
    conclusion VARCHAR(2000),
    insufficient_evidence BOOLEAN,
    confidence DECIMAL(8, 2),
    source_ids VARCHAR(4000),
    failure_type VARCHAR(64),
    requested_actions VARCHAR(2000),
    created_at VARCHAR(32) NOT NULL
);

CREATE TABLE agent_step (
    id VARCHAR(160) PRIMARY KEY,
    agent_run_id VARCHAR(160) NOT NULL,
    run_id VARCHAR(80) NOT NULL,
    step_kind VARCHAR(32) NOT NULL,
    detail VARCHAR(500) NOT NULL,
    created_at VARCHAR(32) NOT NULL
);

CREATE TABLE tool_call (
    id VARCHAR(160) PRIMARY KEY,
    agent_run_id VARCHAR(160) NOT NULL,
    run_id VARCHAR(80) NOT NULL,
    tool_name VARCHAR(64) NOT NULL,
    arguments_json VARCHAR(2000) NOT NULL,
    result_json VARCHAR(8000) NOT NULL,
    source_ids VARCHAR(4000) NOT NULL,
    created_at VARCHAR(32) NOT NULL
);
